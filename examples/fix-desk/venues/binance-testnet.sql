-- Connection: Binance Spot testnet drop copy, a real exchange FIX session (TLS, Ed25519-signed
-- Logon). Needs a testnet Ed25519 API key with FIX_API_READ_ONLY (or FIX_API) and Binance's
-- spot-fix-oe.xml dictionary; see the README. Binance's ExecutionReport has no Account (1), so
-- `account` is the drop-copy session's own CompID.
CREATE SOURCE executions (
    exec_id          VARCHAR,
    order_id         VARCHAR,
    cl_ord_id        VARCHAR,
    account          VARCHAR NOT NULL,
    symbol           VARCHAR NOT NULL,
    side             VARCHAR NOT NULL,
    exec_type        VARCHAR NOT NULL,
    ord_status       VARCHAR NOT NULL,
    order_qty        DECIMAL(18, 8),
    price            DECIMAL(18, 8),
    last_qty         DECIMAL(18, 8),
    last_px          DECIMAL(18, 8),
    cum_qty          DECIMAL(18, 8) NOT NULL,
    leaves_qty       DECIMAL(18, 8),
    text             VARCHAR,
    transact_time    TIMESTAMP NOT NULL,
    _fix_received_at TIMESTAMP NOT NULL,
    _fix_session     VARCHAR NOT NULL,
    _fix_series      BIGINT NOT NULL,
    _fix_seq_num     BIGINT NOT NULL,
    _fix_poss_dup    BOOLEAN NOT NULL,
    _fix_gap_before  BOOLEAN NOT NULL,
    WATERMARK FOR transact_time AS transact_time - INTERVAL '5' SECOND
) FROM FIX (
    host = 'fix-dc.testnet.binance.vision',
    port = '9000',
    venue = 'binance',
    'sender.comp.id' = '${BINANCE_SENDER_COMP_ID:-DESKDC1}',
    'target.comp.id' = 'SPOT',
    username = '${BINANCE_API_KEY}',
    'logon.key.file' = '${BINANCE_KEY_FILE}',
    'dictionary.path' = '${BINANCE_DICTIONARY}',
    messages = '8',
    'journal.path' = '${DESK_DATA}/journal',
    'heartbeat.interval.seconds' = '30',
    'column.exec_id' = '17',
    'column.order_id' = '37',
    'column.cl_ord_id' = '11',
    'column.account' = 'header.56',
    'column.symbol' = '55',
    'column.side' = '54',
    'column.exec_type' = '150',
    'column.ord_status' = '39',
    'column.order_qty' = '38',
    'column.price' = '44',
    'column.last_qty' = '32',
    'column.last_px' = '31',
    'column.cum_qty' = '14',
    'column.leaves_qty' = '151',
    'column.text' = '58',
    'column.transact_time' = '60'
);
